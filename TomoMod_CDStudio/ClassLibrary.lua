local function SpellExists(spellID)
    if not spellID then return false end
    if C_Spell and C_Spell.DoesSpellExist then
        local ok, exists = pcall(C_Spell.DoesSpellExist, spellID)
        if ok and exists == false then return false end
    end
    return true
end

local function RuntimeSpell(spellID, packed)
    if not SpellExists(spellID) then return nil end
    local name = packed and packed[2]
    local icon = packed and packed[3]
    if C_Spell and C_Spell.GetSpellName then
        local ok, value = pcall(C_Spell.GetSpellName, spellID)
        if ok and value and value ~= "" then name = value end
    end
    if C_Spell and C_Spell.GetSpellTexture then
        local ok, value = pcall(C_Spell.GetSpellTexture, spellID)
        if ok and value then icon = value end
    end
    if not name and C_Spell and C_Spell.RequestLoadSpellData then
        pcall(C_Spell.RequestLoadSpellData, spellID)
    end
    return {
        spellID = spellID,
        name = name or ("Spell " .. tostring(spellID)),
        icon = icon,
        spec = (packed and tonumber(packed[1])) or 0,
        known = (CDF.isSpellKnown and CDF.isSpellKnown(spellID)) or false,
    }
end

local function SpecName(specID, fallback)
    if GetSpecializationInfoByID then
        local ok, id, name = pcall(GetSpecializationInfoByID, specID)
        if ok and id and name and name ~= "" then return name end
    end
    return fallback or ("Spec " .. tostring(specID))
end

local function SortSpells(group)
    table.sort(group.spells, function(a, b)
        local an = string.lower(a.name or "")
        local bn = string.lower(b.name or "")
        if an == bn then return (a.spellID or 0) < (b.spellID or 0) end
        return an < bn
    end)
end

local function ActiveSpecID()
    if not (GetSpecialization and GetSpecializationInfo) then return 0 end
    local idx = GetSpecialization()
    if not idx then return 0 end
    return tonumber((GetSpecializationInfo(idx))) or 0
end

local function GroupForLiveScan(data, group, activeSpecID)
    local off = tonumber(group and group.offSpecID) or 0
    if off > 0 then return off end
    local name = group and group.name or ""
    for specID, fallback in pairs(data.specs or {}) do
        if name == fallback or name == SpecName(specID, fallback) then
            return tonumber(specID) or 0
        end
    end
    -- The live scanner's Talents group represents the active loadout.
    if name == "Talents" then return activeSpecID or 0 end
    return 0
end

function CDF.GetStudioLibrary(classToken)
    classToken = classToken or CDF.PlayerClass()
    local data = DATA[classToken]
    if not data then return {} end

    local groups, bySpec, seen = {}, {}, {}
    local shared = {
        name = Loc("cds_lib_group_shared", "Shared class spells"),
        offSpecID = 0,
        spells = {},
    }
    groups[#groups + 1] = shared

    for _, specID in ipairs(data.specOrder or {}) do
        local g = {
            name = SpecName(specID, data.specs and data.specs[specID]),
            offSpecID = specID,
            spells = {},
        }
        bySpec[specID] = g
        groups[#groups + 1] = g
    end

    local function Add(spellID, packed, forcedSpec)
        spellID = tonumber(spellID)
        if not spellID or seen[spellID] then return end
        local rec = RuntimeSpell(spellID, packed)
        if not rec then return end
        if forcedSpec ~= nil then rec.spec = tonumber(forcedSpec) or 0 end
        seen[spellID] = true
        local g = bySpec[rec.spec] or shared
        g.spells[#g.spells + 1] = rec
    end

    -- Collected 12.1.0 data: exactly the spellbook/talent spells seen on the
    -- user's 13 classes and all scanned specializations.
    for spellID, packed in pairs(data.spells or {}) do
        Add(spellID, packed)
    end

    -- Future-proof only the logged-in class. This can contribute genuinely
    -- new spellbook/talent IDs after a patch, without ever restoring the old
    -- hand-written catalog that caused stale/wrong abilities to remain.
    if classToken == CDF.PlayerClass() and CDF.ScanSpellbook then
        local activeSpecID = ActiveSpecID()
        CDF._libCache = nil
        for _, liveGroup in ipairs(CDF.ScanSpellbook() or {}) do
            local specID = GroupForLiveScan(data, liveGroup, activeSpecID)
            for _, spell in ipairs(liveGroup.spells or {}) do
                Add(spell.spellID, { specID, spell.name, spell.icon }, specID)
            end
        end
    end

    for i = #groups, 1, -1 do
        local g = groups[i]
        if #g.spells == 0 then
            table.remove(groups, i)
        else
            SortSpells(g)
        end
    end
    return groups
end

