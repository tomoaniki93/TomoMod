-- =====================================================================
-- Locale_Modules.lua — Libellés du registre de modules (6 langues)
-- ---------------------------------------------------------------------
-- Source unique des chaînes consommées par Core/ModuleManifest.lua :
--   • mod_group_*  les neuf groupes repliables
--   • mod_<clé>    le libellé d'un module
--   • mod_<clé>_*  les sous-bascules des modules composites
--
-- Chargé dans la section Locales du .toc, donc AVANT Core, pour que les
-- manifestes trouvent leurs clés au moment où ils se déclarent.
--
-- Le metatable de localisation renvoie la clé brute pour une clé absente,
-- donc « L[k] or fallback » ne protège de rien : chaque clé doit exister
-- dans les six langues. Tools/test_module_manifest_static.lua verrouille
-- cette parité et échoue si une seule langue en manque une.
--
-- enUS est le socle de repli ; les cinq autres le surchargent quand la
-- locale du client correspond.
-- =====================================================================

